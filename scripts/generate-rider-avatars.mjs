import { readFile, mkdir, writeFile, copyFile, stat } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';
import { Style, Avatar } from '@dicebear/core';
import loreleiNeutralDefinition from '@dicebear/styles/lorelei-neutral.json' with { type: 'json' };
import sharp from 'sharp';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const catalog = JSON.parse(await readFile(join(root, 'shared', 'riderAvatarCatalog.json'), 'utf8'));
const packageJson = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
const sharedDir = join(root, 'shared', 'rider-avatars');
const mobileDir = join(root, 'mobile-app', 'assets', 'rider-avatars');
const webDir = join(root, 'public', 'rider-avatars');

if (!Array.isArray(catalog) || catalog.length !== 8) {
  throw new Error('Rider avatar catalog must contain exactly eight entries');
}

const ids = new Set();
const seeds = new Set();
const files = new Set();
for (const [index, entry] of catalog.entries()) {
  const suffix = String(index + 1).padStart(2, '0');
  if (
    entry?.id !== `avatar_${suffix}` ||
    entry?.seed !== `rider-avatar-${suffix}` ||
    entry?.file !== `avatar_${suffix}.png`
  ) {
    throw new Error(`Invalid catalog record at index ${index}`);
  }
  if (ids.has(entry.id) || seeds.has(entry.seed) || files.has(entry.file)) {
    throw new Error(`Duplicate rider avatar ID, seed, or filename at index ${index}`);
  }
  ids.add(entry.id);
  seeds.add(entry.seed);
  files.add(entry.file);
}

if (loreleiNeutralDefinition.meta.license.name !== 'CC0 1.0') {
  throw new Error('Unexpected Lorelei Neutral license');
}

await Promise.all([sharedDir, mobileDir, webDir].map((dir) => mkdir(dir, { recursive: true })));

const style = new Style(loreleiNeutralDefinition);
for (const { id, seed, file } of catalog) {
  const svg = new Avatar(style, { seed, size: 128 }).toString();
  const png = await sharp(Buffer.from(svg)).resize(128, 128).png().toBuffer();
  if (png.length === 0) throw new Error(`Empty generated PNG for ${id}`);
  const source = join(sharedDir, file);
  await writeFile(source, png);
  await Promise.all([mobileDir, webDir].map((dir) => copyFile(source, join(dir, file))));
  for (const dir of [sharedDir, mobileDir, webDir]) {
    if ((await stat(join(dir, file))).size === 0) {
      throw new Error(`Missing or empty avatar output: ${join(dir, file)}`);
    }
  }
}

const versions = packageJson.devDependencies;
const notice = `# Rider avatar artwork\n\n` +
  `These eight 128 × 128 PNGs were generated from DiceBear's Lorelei Neutral style using fixed, non-personal seeds in \`shared/riderAvatarCatalog.json\`.\n\n` +
  `- Style: [Lorelei Neutral](${loreleiNeutralDefinition.meta.source.url})\n` +
  `- Artist: [${loreleiNeutralDefinition.meta.creator.name}](${loreleiNeutralDefinition.meta.creator.url})\n` +
  `- Artwork license: [${loreleiNeutralDefinition.meta.license.name}](${loreleiNeutralDefinition.meta.license.url})\n` +
  `- Generator: \`@dicebear/core ${versions['@dicebear/core']}\`, \`@dicebear/styles ${versions['@dicebear/styles']}\`, \`sharp ${versions.sharp}\`\n` +
  `- Regenerate locally with \`node scripts/generate-rider-avatars.mjs\`. Avatar generation and rendering make no third-party image requests.\n`;
await Promise.all([sharedDir, mobileDir, webDir].map((dir) => writeFile(join(dir, 'NOTICE.md'), notice)));

const idUnion = catalog.map(({ id }) => JSON.stringify(id)).join(' | ');
const header = '// Generated by scripts/generate-rider-avatars.mjs. Do not edit by hand.\n';
const mobileMap = catalog.map(({ id, file }) => `  ${id}: require('./${file}'),`).join('\n');
await writeFile(join(mobileDir, 'catalog.generated.ts'), `${header}import type { ImageSourcePropType } from 'react-native';\n\nexport type RiderAvatarId = ${idUnion};\n\nconst sources: Record<RiderAvatarId, ImageSourcePropType> = {\n${mobileMap}\n};\n\nexport function getRiderAvatarSource(avatarId: string | null | undefined): ImageSourcePropType | null {\n  return typeof avatarId === 'string' && Object.prototype.hasOwnProperty.call(sources, avatarId)\n    ? sources[avatarId as RiderAvatarId]\n    : null;\n}\n`);

const webMap = catalog.map(({ id, file }) => `  ${id}: '/rider-avatars/${file}',`).join('\n');
await writeFile(join(root, 'src', 'app', 'utils', 'riderAvatarCatalog.generated.ts'), `${header}export type RiderAvatarId = ${idUnion};\n\nconst urls: Record<RiderAvatarId, string> = {\n${webMap}\n};\n\nexport function getRiderAvatarUrl(avatarId: string | null | undefined): string | null {\n  return typeof avatarId === 'string' && Object.prototype.hasOwnProperty.call(urls, avatarId)\n    ? urls[avatarId as RiderAvatarId]\n    : null;\n}\n`);

const serverIds = catalog.map(({ id }) => `  '${id}',`).join('\n');
await writeFile(join(root, 'server', 'services', 'riderAvatarCatalog.generated.ts'), `${header}export const RIDER_AVATAR_IDS = [\n${serverIds}\n] as const;\n\nexport type RiderAvatarId = (typeof RIDER_AVATAR_IDS)[number];\n\nconst allowedAvatarIds: ReadonlySet<string> = new Set(RIDER_AVATAR_IDS);\n\nexport function isRiderAvatarId(value: unknown): value is RiderAvatarId {\n  return typeof value === 'string' && allowedAvatarIds.has(value);\n}\n`);

console.log(`Generated ${catalog.length} rider avatars and platform catalogs.`);
